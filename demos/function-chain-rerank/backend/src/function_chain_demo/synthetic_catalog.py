"""Fictional e-commerce catalog definition for the Function Chain demo.

This module is the single source of truth for the synthetic catalog. Nothing
here is derived from a real retailer: product identifiers, brand names, titles,
descriptions, and bullet points are all invented for the demo, and every field
is marked ``synthetic`` in the generated provenance.

Layout is kept intentionally compatible with the rest of the pipeline:
- 20 product types, 240 products total. The first 120 rows keep the exact
  intent-curation layout below; an appended expansion pass adds six
  ``catalog_background`` products to every one of the 20 types.
- 6 intent types carry ``strong`` / ``partial`` / ``intra_type_hard_negative``
  labels that a plain reading of the text can explain.
- 14 background types are all ``catalog_background``; the expansion rows are
  also ``catalog_background`` and may appear inside the six intent types.
- Each product carries a deterministic operational profile tier (H/G/S/N/R)
  used only to shape fictional rating/inventory/return/age signals.

``validate()`` asserts the quotas so a typo cannot silently break the pipeline.
"""


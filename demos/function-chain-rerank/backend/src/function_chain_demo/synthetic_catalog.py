def build_items() -> list[dict[str, object]]:
    """Assemble the 240-product catalog with stable synthetic IDs and paths."""
    rows = list(
        _DESK + _RUG + _BACKPACK + _HEADPHONES + _UMBRELLA + _BED + _BACKGROUND + _EXPANSION
    )
    items: list[dict[str, object]] = []
    sequence = 0
    seen_ids: set[str] = set()
    for row in rows:
        sequence += 1
        product_type = str(row["product_type"])
        item_id = f"SYN-{product_type}-{sequence:03d}"
        assert item_id not in seen_ids, f"duplicate id {item_id}"
        seen_ids.add(item_id)
        items.append(
            {
                "id": item_id,
                "sequence": sequence,
                "product_type": product_type,
                "selection_class": row["selection_class"],
                "selection_reason": row["selection_reason"],
                "profile": row["profile"],
                "brand": row["brand"],
                "title": row["title"],
                "color": row["color"],
                "material": row["material"],
                "style": row["style"],
                "node_name": f"Catalog > {TYPE_DISPLAY[product_type]}",
                "description": row["description"],
                "bullet_points": list(row["bullet_points"]),
            }
        )
    return items


def validate(items: list[dict[str, object]] | None = None) -> dict[str, object]:
    """Assert catalog quotas and label distribution; return a summary."""
    items = items if items is not None else build_items()
    from function_chain_demo.catalog_curation import (
        SELECTION_LABEL_COUNTS,
        TYPE_ITEM_COUNTS,
    )

    type_counts: dict[str, int] = {}
    label_counts: dict[str, dict[str, int]] = {}
    ids = [str(item["id"]) for item in items]
    assert len(ids) == len(set(ids)), "duplicate ids"
    for item in items:
        product_type = str(item["product_type"])
        label = str(item["selection_class"])
        type_counts[product_type] = type_counts.get(product_type, 0) + 1
        label_counts.setdefault(product_type, {})
        label_counts[product_type][label] = label_counts[product_type].get(label, 0) + 1

    assert len(items) == 240, f"expected 240 items, got {len(items)}"
    assert type_counts == TYPE_ITEM_COUNTS, f"type counts mismatch: {type_counts}"
    for product_type, expected in SELECTION_LABEL_COUNTS.items():
        actual = label_counts.get(product_type, {})
        assert actual.get("strong", 0) == expected["strong"], (product_type, actual)
        assert actual.get("partial", 0) == expected["partial"], (product_type, actual)
        assert actual.get("intra_type_hard_negative", 0) == expected["intra_type_hard_negative"], (
            product_type,
            actual,
        )
    return {
        "items": len(items),
        "unique_ids": len(set(ids)),
        "product_types": len(type_counts),
        "type_counts": type_counts,
        "label_counts": label_counts,
    }


if __name__ == "__main__":
    import json

    summary = validate()
